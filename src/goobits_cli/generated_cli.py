class ConfigManager:
    """Manage CLI configuration."""

    def __init__(self, config_file: Optional[Path] = None):
        """Initialize configuration manager."""
        self.section = "goobits"
        if config_file is None:
            env_path = os.environ.get("MATILDA_CONFIG")
            config_file = Path(env_path) if env_path else Path.home() / ".matilda" / "config.toml"

        self.config_file = Path(config_file)
        self.config_file.parent.mkdir(parents=True, exist_ok=True)
        self.config = self._load_config()

    def _load_config(self) -> Dict[str, Any]:
        """Load configuration from file."""
        if self.config_file.exists():
            try:
                parser = tomllib if tomllib is not None else toml
                with open(self.config_file, "rb") as f:
                    full_config = parser.load(f)
                section = full_config.get(self.section)
                if isinstance(section, dict):
                    return section
                return {}
            except Exception as e:
                logger.warning(f"Failed to load config: {e}")
                return {}
        return {}

    def save_config(self) -> bool:
        """Save configuration to file."""
        try:
            parser = tomllib if tomllib is not None else toml
            if self.config_file.exists():
                with open(self.config_file, "rb") as f:
                    full_config = parser.load(f)
            else:
                full_config = {}

            full_config[self.section] = self.config
            if toml is None:
                logger.error("Failed to save config: 'toml' package is required for writing TOML files.")
                return False
            with open(self.config_file, "w", encoding="utf-8") as f:
                f.write(toml.dumps(full_config))
            return True
        except Exception as e:
            logger.error(f"Failed to save config: {e}")
            return False

    def get(self, key: str, default: Any = None) -> Any:
        """Get configuration value."""
        keys = key.split(".")
        value = self.config
        for k in keys:
            if isinstance(value, dict):
                value = value.get(k)
                if value is None:
                    return default
            else:
                return default
        return value

    def set(self, key: str, value: Any):
        """Set configuration value."""
        keys = key.split(".")
        config = self.config
        for k in keys[:-1]:
            if k not in config:
                config[k] = {}
            config = config[k]
        config[keys[-1]] = value

